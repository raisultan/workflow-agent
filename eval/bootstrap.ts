/**
 * Bootstraps the eval's local services (`T11.7`). Synthetic data only; nothing here is a real account.
 *
 *   node eval/bootstrap.ts              writes eval/.state/services.env (generated passwords and the mock GitLab's token) if missing
 *   node eval/bootstrap.ts --provision  then, with the services up, provisions Mattermost (people, the bot, a team, two channels)
 *                                       and writes eval/.state/workbench.env for the workbench's container
 *
 * Every password and token is generated here, kept in eval/.state/ (git-ignored, mode 0600), and never printed: the script prints
 * variable names only.
 */
import { randomBytes } from 'node:crypto'
import { chmodSync, existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

export const EVAL_DIR = dirname(fileURLToPath(import.meta.url))
export const STATE_DIR = join(EVAL_DIR, '.state')
const SERVICES_ENV = join(STATE_DIR, 'services.env')
const WORKBENCH_ENV = join(STATE_DIR, 'workbench.env')

/** The synthetic people, and the channels each repository's jobs start in. */
export const PEOPLE = [
  { username: 'dev-ivan', email: 'ivan@example.test', firstName: 'Иван', lastName: 'Петров' },
  { username: 'lead-1', email: 'lead@example.test', firstName: 'Алексей', lastName: 'Тимлид' },
] as const
export const BOT = { username: 'workbench', email: 'bot@example.test', firstName: 'Agent', lastName: 'Workbench' }
export const CHANNELS = { node: 'orders-node', python: 'orders-python' } as const

export function readEnv(path: string): Record<string, string> {
  if (!existsSync(path)) return {}
  return Object.fromEntries(readFileSync(path, 'utf8').split('\n').flatMap(line => {
    const match = /^([A-Z0-9_]+)=(.*)$/u.exec(line.trim())
    return match ? [[match[1]!, match[2]!]] : []
  }))
}

function writeEnv(path: string, values: Record<string, string>, header: string): void {
  mkdirSync(STATE_DIR, { recursive: true, mode: 0o700 })
  writeFileSync(path, `# ${header}\n${Object.entries(values).map(([key, value]) => `${key}=${value}`).join('\n')}\n`, { mode: 0o600 })
  chmodSync(path, 0o600)
}

const secret = (bytes = 24) => randomBytes(bytes).toString('base64url')

/** The services' settings: generated once, then kept. */
export function servicesEnv(): Record<string, string> {
  const existing = readEnv(SERVICES_ENV)
  const values = {
    EVAL_POSTGRES_PASSWORD: existing.EVAL_POSTGRES_PASSWORD ?? secret(),
    // Mattermost wants an upper-case letter, a digit and a symbol.
    EVAL_USER_PASSWORD: existing.EVAL_USER_PASSWORD ?? `Ev-${secret(18)}9`,
    EVAL_GITLAB_TOKEN: existing.EVAL_GITLAB_TOKEN ?? `mock-${secret()}`,
    EVAL_MATTERMOST_PORT: existing.EVAL_MATTERMOST_PORT ?? '8065',
    EVAL_JIRA_PORT: existing.EVAL_JIRA_PORT ?? '25411',
    EVAL_GITLAB_PORT: existing.EVAL_GITLAB_PORT ?? '8929',
  }
  if (Object.entries(values).some(([key, value]) => existing[key] !== value)) writeEnv(SERVICES_ENV, values, 'Generated by eval/bootstrap.ts; local test values only.')
  return values
}

interface Response<T> { status: number; headers: Headers; data: T }
async function mm<T>(baseUrl: string, path: string, options: { method?: string; token?: string; body?: unknown } = {}): Promise<Response<T>> {
  const response = await fetch(`${baseUrl}${path}`, { method: options.method ?? 'GET', headers: { 'Content-Type': 'application/json', Accept: 'application/json',
    ...options.token ? { Authorization: `Bearer ${options.token}` } : {} }, ...options.body !== undefined ? { body: JSON.stringify(options.body) } : {} })
  const text = await response.text()
  return { status: response.status, headers: response.headers, data: (text ? JSON.parse(text) : {}) as T }
}

/** Logs in as a synthetic person (or the bot) and returns the session token. */
export async function login(baseUrl: string, username: string, password: string): Promise<{ id: string; token: string }> {
  const response = await mm<{ id: string }>(baseUrl, '/api/v4/users/login', { method: 'POST', body: { login_id: username, password } })
  if (response.status !== 200) throw new Error(`could not log in as ${username}: HTTP ${response.status}`)
  return { id: response.data.id, token: response.headers.get('Token') ?? '' }
}

async function ensureUser(baseUrl: string, person: { username: string; email: string; firstName: string; lastName: string }, password: string, adminToken?: string) {
  const existing = await mm<{ id: string }>(baseUrl, '/api/v4/users/login', { method: 'POST', body: { login_id: person.username, password } })
  if (existing.status === 200) return { id: existing.data.id, token: existing.headers.get('Token') ?? '' }
  const created = await mm<{ id: string; message?: string }>(baseUrl, '/api/v4/users', { method: 'POST', ...adminToken ? { token: adminToken } : {},
    body: { username: person.username, email: person.email, password, first_name: person.firstName, last_name: person.lastName } })
  if (created.status !== 201) throw new Error(`could not create ${person.username}: HTTP ${created.status} ${created.data.message ?? ''}`)
  return login(baseUrl, person.username, password)
}

async function provision(services: Record<string, string>): Promise<void> {
  const baseUrl = `http://127.0.0.1:${services.EVAL_MATTERMOST_PORT}`
  for (let waited = 0; ; waited += 1500) {
    const ping = await fetch(`${baseUrl}/api/v4/system/ping`).then(response => response.ok, () => false)
    if (ping) break
    if (waited > 180_000) throw new Error(`Mattermost at ${baseUrl} did not start`)
    await new Promise(resolve => setTimeout(resolve, 1500))
  }
  const password = services.EVAL_USER_PASSWORD!
  // The first user Mattermost creates is its system admin.
  const ivan = await ensureUser(baseUrl, PEOPLE[0], password)
  const admin = ivan.token
  await mm(baseUrl, '/api/v4/config/patch', { method: 'PUT', token: admin, body: { ServiceSettings: { EnableUserAccessTokens: true, EnableBotAccountCreation: true },
    TeamSettings: { EnableOpenServer: true } } })
  const lead = await ensureUser(baseUrl, PEOPLE[1], password, admin)
  const bot = await ensureUser(baseUrl, BOT, password, admin)
  await mm(baseUrl, `/api/v4/users/${bot.id}/roles`, { method: 'PUT', token: admin, body: { roles: 'system_user system_admin' } })
  const pat = await mm<{ token?: string }>(baseUrl, `/api/v4/users/${bot.id}/tokens`, { method: 'POST', token: admin, body: { description: `eval-${Date.now()}` } })
  if (pat.status !== 200 || !pat.data.token) throw new Error(`could not create the bot's access token: HTTP ${pat.status}`)
  let team = await mm<{ id?: string }>(baseUrl, '/api/v4/teams/name/engineering', { token: admin })
  if (team.status !== 200) team = await mm<{ id: string }>(baseUrl, '/api/v4/teams', { method: 'POST', token: admin, body: { name: 'engineering', display_name: 'Engineering', type: 'O' } })
  const teamId = team.data.id!
  for (const id of [ivan.id, lead.id, bot.id]) await mm(baseUrl, `/api/v4/teams/${teamId}/members`, { method: 'POST', token: admin, body: { team_id: teamId, user_id: id } })
  const channels: Record<string, string> = {}
  for (const [key, name] of Object.entries(CHANNELS)) {
    let channel = await mm<{ id?: string }>(baseUrl, `/api/v4/teams/${teamId}/channels/name/${name}`, { token: admin })
    if (channel.status !== 200) channel = await mm<{ id: string }>(baseUrl, '/api/v4/channels', { method: 'POST', token: admin,
      body: { team_id: teamId, name, display_name: `Orders (${key})`, purpose: `Jobs for the synthetic ${key} repository`, type: 'O' } })
    channels[key] = channel.data.id!
    for (const id of [ivan.id, lead.id, bot.id]) await mm(baseUrl, `/api/v4/channels/${channels[key]}/members`, { method: 'POST', token: admin, body: { user_id: id } })
  }
  writeEnv(WORKBENCH_ENV, {
    MATTERMOST_BASE_URL: `http://host.docker.internal:${services.EVAL_MATTERMOST_PORT}`, MATTERMOST_TOKEN: pat.data.token, MATTERMOST_BOT_USER_ID: bot.id,
    MATTERMOST_TEAM_ID: teamId, JIRA_BASE_URL: `http://host.docker.internal:${services.EVAL_JIRA_PORT}`, JIRA_TOKEN: 'mock-jira-accepts-any-token',
    GITLAB_BASE_URL: `http://host.docker.internal:${services.EVAL_GITLAB_PORT}`, GITLAB_TOKEN: services.EVAL_GITLAB_TOKEN!,
    EVAL_CHANNEL_NODE: channels.node!, EVAL_CHANNEL_PYTHON: channels.python!, WORKBENCH_ALLOWED_SENDERS: 'dev-ivan,lead-1',
  }, 'Generated by eval/bootstrap.ts --provision; the workbench container\'s connector settings for the local eval services.')
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const services = servicesEnv()
  console.log(`${SERVICES_ENV}: ${Object.keys(services).join(', ')}`)
  if (process.argv.includes('--provision')) {
    await provision(services)
    console.log(`${WORKBENCH_ENV}: ${Object.keys(readEnv(WORKBENCH_ENV)).join(', ')}`)
  }
}
